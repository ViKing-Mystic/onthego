    parseTimeToMinutes(timeStr) {
      if (!timeStr) return 0;
      const match = timeStr.match(/(\d+):(\d+)\s*(AM|PM)?/i);
      if (!match) return 0;
      let hours = parseInt(match[1], 10);
      const minutes = parseInt(match[2], 10);
      const period = match[3] ? match[3].toUpperCase() : "AM";
      if (period === "PM" && hours < 12) hours += 12;
      if (period === "AM" && hours === 12) hours = 0;
      return hours * 60 + minutes;
    },

    formatMinutesToTime(mins) {
      let h = Math.floor(mins / 60) % 24;
      const m = mins % 60;
      const period = h >= 12 ? "PM" : "AM";
      if (h > 12) h -= 12;
      if (h === 0) h = 12;
      return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')} ${period}`;
    },

    getNextDeparture(direction, afterTimeStr) {
      const list = this.timetable20Oct[direction] || [];
      const afterMins = this.parseTimeToMinutes(afterTimeStr);
      for (const t of list) {
        if (this.parseTimeToMinutes(t) >= afterMins) {
          return t;
        }
      }
      return null;
    },

