  /**
   * Bayesian Weighted Review Scoring Algorithm:
   * (v / (v + m)) * R + (m / (v + m)) * C
   * Ensures that a 4.8 with 5 reviews does NOT outrank a well-established 4.5 with 2,500 reviews.
   *
   * @param {number} rating Venue average rating (e.g. 4.5)
   * @param {number} reviewCount Number of reviews (e.g. 2470)
   * @returns {number} Bayesian weighted score
   */
  calculateBayesianReviewScore(rating, reviewCount) {
    const v = Math.max(0, parseInt(reviewCount, 10) || 0);
    const R = Math.max(1, Math.min(5, parseFloat(rating) || 4.0));
    const m = this.BAYESIAN_MIN_REVIEWS;
    const C = this.BAYESIAN_PRIOR_RATING;

    const weightedScore = ((v / (v + m)) * R) + ((m / (v + m)) * C);
    return parseFloat(weightedScore.toFixed(3));
  },

  /**
   * Validates opening hour compatibility against a target date and time.
   * @param {Object} dest
   * @param {string} dayOfWeek e.g. "Friday", "Saturday"
   * @param {string} timeStr e.g. "02:00 PM"
   * @returns {Object} { isOpen: boolean, reason: string }
   */
  checkOpeningCompatibility(dest, dayOfWeek, timeStr) {
    if (dest.status === "reported_closed") {
      return { isOpen: false, reason: "Reported permanently closed in available listings" };
    }

    // Special checks with specific authoritative reasons
    if ((dest.id === "dest_dutchpalace" || dest.name?.includes("Dutch Palace")) && dayOfWeek === "Friday") {
      return { isOpen: false, reason: "Dutch Palace is closed every Friday" };
    }
    if ((dest.id === "dest_synagogue" || dest.name?.includes("Synagogue")) && (dayOfWeek === "Friday" || dayOfWeek === "Saturday")) {
      return { isOpen: false, reason: "Paradesi Synagogue is closed Friday afternoons & all day Saturday for Shabbat" };
    }
    if ((dest.id === "dest_ambalappuzha" || dest.name?.includes("Ambalappuzha")) && timeStr) {
      const isAfternoon = timeStr.includes("12:") || timeStr.includes("01:") || timeStr.includes("02:") || timeStr.includes("03:") || timeStr.includes("04:") || timeStr.includes("13:") || timeStr.includes("14:") || timeStr.includes("15:") || timeStr.includes("16:");
      if (isAfternoon && (timeStr.includes("PM") || parseInt(timeStr) >= 12)) {
        return { isOpen: false, reason: "Temple closed in the afternoon (12:00 PM - 05:00 PM)" };
      }
    }

    if (dest.closureDays && dest.closureDays.includes(dayOfWeek)) {
      return { isOpen: false, reason: `Closed on ${dayOfWeek}s (${dest.openingHours})` };
    }

    return { isOpen: true, reason: "Compatible with requested day and time" };
  },

